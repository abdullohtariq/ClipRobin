const CANONICAL_STYLE_IDS = new Set<string>(CAPTION_STYLE_OPTIONS.map((s) => s.id));

export function normalizeCaptionStyle(raw: string | null | undefined): CaptionStyle {
  if (raw === "bold_emerald") return "robin";
  if (raw === "clean_gold") return "clean";
  if (raw && CANONICAL_STYLE_IDS.has(raw)) {
    return raw as CaptionStyle;
  }
  return "classic";
}

export function getCaptionStyleOption(styleId: CaptionStyle): StyleOption {
  const canonical = normalizeCaptionStyle(styleId);
  return CAPTION_STYLE_OPTIONS.find((s) => s.id === canonical) ?? CAPTION_STYLE_OPTIONS[0];
}
